const ALL_SCENARIOS: SimScenario[] = [
  JUDGE_SCENARIO,
  PROSECUTOR_SCENARIO,
  POLICE_SCENARIO,
  ADMIN_SCENARIO,
  AUDITOR_SCENARIO,
  QUALITY_SCENARIO,
  STRATEGY_SCENARIO,
];

export function findScenario(sectorId: string, professionId: string): SimScenario | undefined {
  return ALL_SCENARIOS.find(
    (s) => s.sectorId === sectorId && s.professionId === professionId,
  );
}

export function listScenarios(): SimScenario[] {
  return ALL_SCENARIOS;
}
