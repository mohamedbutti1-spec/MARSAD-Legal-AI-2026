export async function seedProfessionalWorkflows(): Promise<void> {
  let inserted = 0;

  for (const step of STEPS) {
    const existsResult = await db.execute<{ n: string }>(
      sql`SELECT COUNT(*)::text AS n
          FROM pgf_workflow_steps
          WHERE sector_id     = ${step.sectorId}
            AND profession_id = ${step.professionId}
            AND stage_id      = ${step.stageId}
            AND title         = ${step.title}`,
    );
    if (parseInt(existsResult.rows[0]?.n ?? "0", 10) > 0) continue;

    await db.insert(pgfWorkflowStepsTable).values({
      sectorId:           step.sectorId,
      professionId:       step.professionId,
      stageId:            step.stageId,
      order:              step.order,
      title:              step.title,
      objective:          step.objective,
      nextAction:         step.nextAction,
      requiredDocuments:  j(step.requiredDocuments),
      approvals:          j(step.approvals),
      checkpoints:        j(step.checkpoints),
      branchRules:        j(step.branchRules),
      escalationRules:    j(step.escalationRules),
      expectedOutput:     step.expectedOutput,
      estimatedDuration:  step.estimatedDuration,
    });
    inserted++;
  }

  logger.info(`PWE seed: ${inserted} workflow steps inserted`);
}
